#!/usr/bin/env python3
"""Mechanically combine the preserved B2 chassis and supplied Huibo arm.

The vendor package is left untouched. Zero effort/velocity limits in that
description are replaced ONLY in the generated simulation asset. These are
provisional simulation limits, not Huibo hardware specifications.
"""

from __future__ import annotations

import argparse
from copy import deepcopy
from pathlib import Path
import xml.etree.ElementTree as ET


PROJECT = Path(__file__).resolve().parents[2]
ASSETS = PROJECT / "source/b2_z1/b2_z1/assets/b2_z1"
ARM_JOINTS = tuple(f"right_joint{i}" for i in range(1, 8))


def combine(chassis_path: Path, arm_path: Path) -> ET.Element:
    source = ET.parse(chassis_path).getroot()
    vendor = ET.parse(arm_path).getroot()
    result = ET.Element("robot", name="b2_huibo")
    result.append(ET.Comment(
        " Generated by scripts/assets/build_b2_huibo.py. Original B2 and Huibo "
        "descriptions are preserved. Huibo CAD mass/inertias/axes/position "
        "limits are unchanged; 30 Nm / 1.5 rad/s are simulation-only limits. "
    ))
    # Keep the entire connected B2 tree, excluding the old Z1 root and tool.
    old_arm_links = {"link00", "link01", "link02", "link03", "link04", "link05",
                     "link06", "link_mounter", "link_gun", "dummy_target"}
    for element in source:
        if element.tag == "link" and element.get("name") in old_arm_links:
            continue
        if element.tag == "joint":
            if (element.find("parent").get("link") in old_arm_links
                    or element.find("child").get("link") in old_arm_links):
                continue
        result.append(deepcopy(element))
    result.append(ET.Comment(
        " Rotate the source right-shoulder mounting axis onto B2 +Z. "
        "The mounting surface bottom is z=0.09 m, 0.10 m aft of B2 centre. "
    ))
    for element in vendor:
        if element.tag == "link" and element.get("name") == "world":
            continue
        node = deepcopy(element)
        for mesh in node.iter("mesh"):
            filename = mesh.get("filename", "")
            if not filename.startswith("package://huibo_description/"):
                raise ValueError(f"unexpected vendor mesh URI: {filename}")
            mesh.set("filename", filename.replace("package://", "", 1))
        if node.tag == "joint" and node.get("name") == "right_joint0":
            node.find("parent").set("link", "base_link")
            node.find("origin").set("xyz", "-0.10 0 -0.014")
            node.find("origin").set("rpy", "-1.5707963267948966 0 3.141592653589793")
            node.set("dont_collapse", "true")
        if node.tag == "joint" and node.get("name") in ARM_JOINTS:
            limit = node.find("limit")
            if float(limit.get("effort")) != 0 or float(limit.get("velocity")) != 0:
                raise ValueError("vendor drive limits changed; review simulation overrides")
            limit.set("effort", "30")
            limit.set("velocity", "1.5")
        result.append(node)
    # Retain optical fiducial and TCP coordinates used by the RGB-D bridge.
    # Turn the external adapter (not a vendor joint/axis): gun -Z must be
    # coaxial with the flange's forward +X for a top-down, axial tool grip.
    # The +0.03 Y shift cancels the preserved gun/TCP's -0.03 Y offset.
    for name in ("link_gun", "dummy_target"):
        node = next(deepcopy(link) for link in source.findall("link") if link.get("name") == name)
        if name == "link_gun":
            # A visible, collidable simulation adapter bridges the preserved
            # flange offset and the shortened gun's upper face. It belongs
            # to this existing tool body: no new mass, DOF or vendor edit.
            # In gun coordinates the flange is (0,-0.03,+0.075); the gun's
            # upper face is (0,-0.03,-0.02), hence a 95 mm axial connector.
            for tag in ("visual", "collision"):
                shape = ET.SubElement(node, tag, name="huibo_axial_adapter")
                ET.SubElement(shape, "origin", xyz="0 -0.03 0.0275", rpy="0 0 0")
                geometry = ET.SubElement(shape, "geometry")
                ET.SubElement(geometry, "cylinder", radius="0.022", length="0.095")
                if tag == "visual":
                    material = ET.SubElement(shape, "material", name="huibo_adapter_gray")
                    ET.SubElement(material, "color", rgba="0.35 0.38 0.42 1")
        if name == "dummy_target":
            # PhysX replaces a zero-mass unmerged dynamic frame with an
            # estimated body. Use an explicit negligible positive inertia
            # rather than inheriting an unknown automatically assigned mass.
            node.find("inertial/mass").set("value", "0.000001")
            inertia = node.find("inertial/inertia")
            for axis in ("ixx", "iyy", "izz"):
                inertia.set(axis, "0.000000001")
        result.append(node)
    joint = ET.SubElement(result, "joint", name="huibo_tool_mount", type="fixed", dont_collapse="true")
    ET.SubElement(joint, "parent", link="right_arm_end_link")
    ET.SubElement(joint, "child", link="link_gun")
    ET.SubElement(joint, "origin", xyz="0.075 0.03 0", rpy="0 -1.5707963267948966 0")
    tcp_joint = next(deepcopy(joint) for joint in source.findall("joint")
                     if joint.get("name") == "link_dummy_target_joint")
    result.append(tcp_joint)
    names = [node.get("name") for node in result if node.tag in ("joint", "link")]
    if len(names) != len(set(names)):
        raise ValueError("duplicate joint/link names in combined asset")
    for mesh in result.iter("mesh"):
        if not (ASSETS / mesh.get("filename")).is_file():
            raise FileNotFoundError(mesh.get("filename"))
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ASSETS / "b2_huibo.urdf")
    parser.add_argument("--replace-generated", action="store_true")
    args = parser.parse_args()
    if args.output.exists() and not args.replace_generated:
        raise FileExistsError(f"preserving existing {args.output}; use --replace-generated after review")
    if args.output.resolve() in (
        (ASSETS / "b2_z1_no_stick.urdf").resolve(),
        (ASSETS / "huibo_description/urdf/single_right_hand.urdf").resolve(),
    ):
        raise ValueError("source descriptions must never be overwritten")
    root = combine(ASSETS / "b2_z1_no_stick.urdf", ASSETS / "huibo_description/urdf/single_right_hand.urdf")
    ET.indent(root, space="  ")
    ET.ElementTree(root).write(args.output, encoding="utf-8", xml_declaration=True)
    print(f"Generated {args.output}: 12 B2 joints + 7 Huibo joints; original sources preserved")


if __name__ == "__main__":
    main()
